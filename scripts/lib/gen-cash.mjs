// Generates patches/binary/0004-cash-reward.json from the original libgameDSO.so.
// Owner decision 2026-11-06: Cash per stage clear, enough to buy everything eventually.
// The battle result credits Gold with one call, CInventory::SetGold(inventory, gold + earned), at 0x78af2.
// That call is pointed at a helper which does the same SetGold, then adds earned * CASH_PER_GOLD as Cash
// through CInventory::SetAncientCoin, which keeps the game's own checksum. A loss earns 0 Gold, so 0 Cash.
// The helper lives in CPdStateWorldmap::CallbackPop_TrialChange, which is dead (audit Q1).
// Addresses are Ghidra addresses; the file offset is the address minus 0x10000. Thumb-1 only (ARMv5TE).
// Usage: node gen-cash.mjs <original libgameDSO.so> <out.json>
import fs from 'node:fs';

const [so, out] = process.argv.slice(2);
const b = fs.readFileSync(so);
const BASE = 0x10000;
const CASH_PER_GOLD_SHIFT = Number(process.env.CASH_SHIFT || 1); // Cash = Gold earned << 1, so 2 Cash per Gold. CASH_SHIFT is for test builds only

const SITE = 0x78af2;          // bl CInventory::SetGold, in CPdStateGame::ResultSetting
const HELPER = 0xacf64;        // CPdStateWorldmap::CallbackPop_TrialChange, 144 bytes, no callers
const HELPER_SIZE = 144;
const GET_GOLD = 0x6ee30, SET_GOLD = 0x6eea8, GET_CASH = 0x6ede0, SET_CASH = 0x9d5dc;

const bl = (from, to) => {
  const off = to - (from + 4);
  if (off < -(1 << 22) || off >= 1 << 22 || off & 1) throw new Error(`bl out of range ${from.toString(16)}`);
  return [0xf000 | ((off >> 12) & 0x7ff), 0xf800 | ((off >> 1) & 0x7ff)];
};
const decodeBl = (at) => {
  const h1 = b.readUInt16LE(at - BASE), h2 = b.readUInt16LE(at - BASE + 2);
  if ((h1 & 0xf800) !== 0xf000 || (h2 & 0xf800) !== 0xf800) return null;
  let off = ((h1 & 0x7ff) << 12) | ((h2 & 0x7ff) << 1);
  if (off & (1 << 22)) off -= 1 << 23;
  return at + 4 + off;
};
const hex = (words) => Buffer.from(Uint16Array.from(words).buffer).toString('hex');
const bytes = (at, n) => b.subarray(at - BASE, at - BASE + n).toString('hex');

// Check the encoder against real calls before trusting it.
if (decodeBl(SITE) !== SET_GOLD) throw new Error('0x78af2 is not bl SetGold');
if (decodeBl(0x78ae2) !== GET_GOLD) throw new Error('0x78ae2 is not bl GetGold');
if (hex(bl(SITE, SET_GOLD)) !== bytes(SITE, 4)) throw new Error('bl encoder does not reproduce the original call');

// Helper, Thumb-1. r0 = inventory, r1 = new Gold total. Saves r4-r6 as AAPCS requires.
const code = [];
const at = () => HELPER + code.length * 2;
const emit = (...w) => code.push(...w);
emit(0xb570);                 // push {r4, r5, r6, lr}
emit(0x1c04);                 // adds r4, r0, #0      inventory
emit(0x1c0d);                 // adds r5, r1, #0      new Gold total
emit(...bl(at(), GET_GOLD));  // bl GetGold           r0 = Gold before
emit(0x1a2e);                 // subs r6, r5, r0      Gold earned
emit(0x1c20);                 // adds r0, r4, #0
emit(0x1c29);                 // adds r1, r5, #0
emit(...bl(at(), SET_GOLD));  // bl SetGold           what the game did before
emit(0x2e00);                 // cmp r6, #0
const ble = code.length; emit(0);  // ble done (filled in below)
emit(0x1c20);                 // adds r0, r4, #0
emit(...bl(at(), GET_CASH));  // bl GetAncientCoin    r0 = Cash
emit(0x0031 | (CASH_PER_GOLD_SHIFT << 6)); // lsls r1, r6, #shift
emit(0x1841);                 // adds r1, r0, r1
emit(0x1c20);                 // adds r0, r4, #0
emit(...bl(at(), SET_CASH));  // bl SetAncientCoin    clamps and updates the checksum
const done = code.length;
emit(0xbd70);                 // pop {r4, r5, r6, pc}
const rel = (done - ble) * 2 - 4;
code[ble] = 0xdd00 | ((rel >> 1) & 0xff);
if (code.length * 2 > HELPER_SIZE) throw new Error('helper too large');

const helperAfter = hex(code);
const spec = {
  entry: 'lib/armeabi/libgameDSO.so',
  reason: `Cash per stage clear (owner decision 2026-11-06). The result screen's SetGold call goes through a helper that also adds the Gold earned x${1 << CASH_PER_GOLD_SHIFT} as Cash via SetAncientCoin. The helper sits in the dead CallbackPop_TrialChange. Generated by scripts/lib/gen-cash.mjs.`,
  edits: [
    { offset: '0x' + (SITE - BASE).toString(16), before: bytes(SITE, 4), after: hex(bl(SITE, HELPER)) },
    { offset: '0x' + (HELPER - BASE).toString(16), before: bytes(HELPER, helperAfter.length / 2), after: helperAfter },
  ],
};
fs.writeFileSync(out, JSON.stringify(spec, null, 2) + '\n');
console.log(out, 'helper', code.length * 2, 'bytes');
