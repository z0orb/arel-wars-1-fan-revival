// Writes the JNIEnv slot name table of the debug slot log (PLAN.md TASK-E2.2).
// Usage: node tools/gen-jni-names.mjs JNI_H OUT.cpp
//   JNI_H  the jni.h of the NDK sysroot. Its struct JNINativeInterface gives the slot order:
//          4 reserved words, then one function pointer per slot.
import fs from 'node:fs';

const [jniH, outPath] = process.argv.slice(2);
if (!outPath) throw new Error('usage: gen-jni-names.mjs JNI_H OUT.cpp');
const text = fs.readFileSync(jniH, 'utf8');
const start = text.indexOf('struct JNINativeInterface {');
const end = text.indexOf('};', start);
if (start < 0 || end < 0) throw new Error('no struct JNINativeInterface in ' + jniH);
const body = text.slice(start, end);
const names = ['reserved0', 'reserved1', 'reserved2', 'reserved3'];
for (const m of body.matchAll(/\(\*\s*(\w+)\s*\)\s*\(/g)) names.push(m[1]);
if (names.length < 232 || names[4] !== 'GetVersion' || names[6] !== 'FindClass')
  throw new Error(`unexpected slot list: ${names.length} names, slot 4 ${names[4]}, slot 6 ${names[6]}`);
let out = `// Generated by tools/gen-jni-names.mjs from the NDK jni.h. Do not edit.
#include <cstdint>
namespace emu {
static const char *const jni_names[] = {
${names.map((n) => `    "${n}",`).join('\n')}
};
const char *jni_slot_name(uint32_t slot) { return slot < ${names.length}u ? jni_names[slot] : "?"; }
}  // namespace emu
`;
fs.writeFileSync(outPath, out);
console.log(`gen-jni-names: ${names.length} slots`);
