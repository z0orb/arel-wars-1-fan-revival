// Writes bridge/src/native/leaves.inc: one row per verified DrawOP leaf (PLAN.md DES-12, TASK-E4.3).
// Usage: node tools/gen-native-leaves.mjs ../universal/work/audit/mangled.txt ../universal/spec/verified.tsv bridge/src/native/leaves.inc
// A row: {"mangled name", op, fmt, clip, ints, u16param}. fmt: 0 to 5 as Blit.java, 6 Auto, 7 the
// uncompressed _16 leaf (DrawOP_X_16PtS_...). ints: the count of int arguments after the pointers.
// The regexes are those of universal/desktop/src/arel/desktop/VecRun.java.
import fs from 'node:fs';
const [mangledPath, verifiedPath, out] = process.argv.slice(2);
const OPS = {COPY: 0, BLEND16: 1, ADD: 2, SUB: 3, VOID: 4, LIGHTEN: 6, GRAY: 10, RGB: 11, RGBHALF: 12, RGBADD: 13,
  RGBMULTI: 14, OUTLINE: 15, ENLARGE: 16, FLIP: 17, LIGHTING: 18, FX: 19};
const FMT = {'': 0, _Ex: 1, _16: 2, _Alpha: 3, _Ex_Alpha: 4, _16_Alpha: 5, _Auto: 6};
const LEAF = /^_Z\d+(DrawOP_([A-Z0-9]+)_(Clipping)?Compress_16(_Ex|_16|_Alpha|_Ex_Alpha|_16_Alpha|_Auto)?)PtPhS_(i+)(t?)$/;
const LEAF16 = /^_Z\d+(DrawOP_([A-Z0-9]+)_16)PtS_(i+)$/;
const verified = new Set(fs.readFileSync(verifiedPath, 'utf8').split('\n').filter(l => l.startsWith('DrawOP_')).map(l => l.split('\t')[0]));
const names = [...new Set(fs.readFileSync(mangledPath, 'utf8').match(/_Z\d+DrawOP_\w+/g))].sort();
const rows = [];
const seen = new Set();
for (const n of names) {
  let m = LEAF.exec(n), row;
  if (m) row = {base: m[1], op: OPS[m[2]], fmt: FMT[m[4] ?? ''], clip: m[3] ? 1 : 0, ints: m[5].length, t: m[6] ? 1 : 0};
  else if ((m = LEAF16.exec(n))) row = {base: m[1], op: OPS[m[2]], fmt: 7, clip: 0, ints: m[3].length, t: 0};
  else continue;
  if (!verified.has(row.base)) continue;
  if (row.op === undefined) throw new Error(`unknown op in ${n}`);
  if (seen.has(row.base)) throw new Error(`two symbols for ${row.base}`);
  seen.add(row.base);
  rows.push(`{"${n}", ${row.op}, ${row.fmt}, ${row.clip}, ${row.ints}, ${row.t}},`);
}
const missing = [...verified].filter(v => !seen.has(v));
if (missing.length) throw new Error(`verified leaves without a symbol: ${missing.join(' ')}`);
fs.writeFileSync(out, `// Generated by tools/gen-native-leaves.mjs: ${rows.length} verified DrawOP leaves. Do not edit.\n${rows.join('\n')}\n`);
console.log(`${out}: ${rows.length} leaves`);
