// Writes the host trampolines of the bridge (PLAN.md DES-06).
// Usage: node tools/gen-exports.mjs GUEST.so DEXDUMP.txt OUT.cpp
//   GUEST.so     the 32-bit ARM guest; its .dynsym gives the exports Java_com_gamevil_nexus2_Natives_*
//   DEXDUMP.txt  "dexdump -d" output of the shell classes.dex; it gives the native methods of
//                com.gamevil.nexus2.Natives and their signatures
// Rules: a guest export with no native method in Java fails the build. A native method with no guest
// export gets no trampoline (as in v1: Java then gets UnsatisfiedLinkError on that call).
// Each trampoline passes (guest JNIEnv, class handle, arguments) to the guest with AAPCS rules:
// 64-bit values start on an even word index (a register pair, or an 8-aligned stack slot).
import fs from 'node:fs';

const [soPath, dumpPath, outPath] = process.argv.slice(2);
if (!outPath) throw new Error('usage: gen-exports.mjs GUEST.so DEXDUMP.txt OUT.cpp');
const PREFIX = 'Java_com_gamevil_nexus2_Natives_';
const CLASS = 'Lcom/gamevil/nexus2/Natives;';

// ---- guest exports ----
function guestExports(buf) {
  if (buf.readUInt32BE(0) !== 0x7f454c46 || buf[4] !== 1) throw new Error('not a 32-bit ELF');
  const shoff = buf.readUInt32LE(0x20), shentsize = buf.readUInt16LE(0x2e), shnum = buf.readUInt16LE(0x30);
  const sec = (i) => {
    const o = shoff + i * shentsize;
    return { type: buf.readUInt32LE(o + 4), offset: buf.readUInt32LE(o + 16), size: buf.readUInt32LE(o + 20), link: buf.readUInt32LE(o + 24) };
  };
  const out = [];
  for (let i = 0; i < shnum; i++) {
    const s = sec(i);
    if (s.type !== 11) continue; // SHT_DYNSYM
    const str = sec(s.link);
    for (let p = s.offset + 16; p < s.offset + s.size; p += 16) {
      const nameOff = buf.readUInt32LE(p), shndx = buf.readUInt16LE(p + 14), info = buf[p + 12];
      let e = str.offset + nameOff;
      while (buf[e]) e++;
      const name = buf.toString('latin1', str.offset + nameOff, e);
      if (shndx !== 0 && (info & 0xf) === 2 && name.startsWith(PREFIX)) out.push(name.slice(PREFIX.length));
    }
  }
  return [...new Set(out)].sort();
}

// ---- native methods from dexdump ----
function nativeMethods(text) {
  const m = new Map();
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const head = lines[i].match(/^\s+#\d+\s+: \(in (\S+)\)$/);
    if (!head || head[1] !== CLASS) continue;
    const name = lines[i + 1]?.match(/name\s+: '(.*)'/)?.[1];
    const type = lines[i + 2]?.match(/type\s+: '(.*)'/)?.[1];
    const access = lines[i + 3]?.match(/access\s+: 0x([0-9a-f]+)/)?.[1];
    if (!name || !type || !access) throw new Error(`cannot parse the dexdump method at line ${i + 1}`);
    const flags = parseInt(access, 16);
    if (!(flags & 0x100)) continue; // ACC_NATIVE
    if (m.has(name)) throw new Error(`overloaded native method ${name}: not handled`);
    m.set(name, { type, isStatic: !!(flags & 0x8) });
  }
  return m;
}

// Java type -> C type, guest words, kind.
function parseSig(sig) {
  const mm = sig.match(/^\((.*)\)(.+)$/);
  if (!mm) throw new Error(`bad signature ${sig}`);
  const args = [];
  let s = mm[1];
  while (s.length) {
    let t = s[0], n = 1;
    if (t === 'L') n = s.indexOf(';') + 1;
    else if (t === '[') { while (s[n] === '[') n++; if (s[n] === 'L') n = s.indexOf(';', n) + 1; else n++; }
    args.push(s.slice(0, n));
    s = s.slice(n);
  }
  return { args, ret: mm[2] };
}
function ctype(t) {
  const prim = { Z: 'jboolean', B: 'jbyte', C: 'jchar', S: 'jshort', I: 'jint', J: 'jlong', F: 'jfloat', D: 'jdouble', V: 'void' };
  if (prim[t]) return prim[t];
  if (t === 'Ljava/lang/String;') return 'jstring';
  if (t === '[B') return 'jbyteArray';
  if (t.startsWith('[')) return 'jarray';
  if (t === 'Ljava/lang/Class;') return 'jclass';
  return 'jobject';
}

const exportsList = guestExports(fs.readFileSync(soPath));
const natives = nativeMethods(fs.readFileSync(dumpPath, 'utf8'));
const missingJava = exportsList.filter((n) => !natives.has(n));
if (missingJava.length) {
  console.error(`gen-exports: guest exports with no native method in Java: ${missingJava.join(', ')}`);
  process.exit(1);
}
const noExport = [...natives.keys()].filter((n) => !exportsList.includes(n)).sort();

let out = `// Generated by tools/gen-exports.mjs from the guest .dynsym and the shell dex. Do not edit.
// ${exportsList.length} trampolines. Native methods with no guest export (no trampoline, as in v1): ${noExport.join(', ') || 'none'}.
#include "bridge.h"
using emu::Scope;
`;
for (const name of exportsList) {
  const { type, isStatic } = natives.get(name);
  const { args, ret } = parseSig(type);
  const params = ['JNIEnv *env', isStatic ? 'jclass self' : 'jobject self'];
  const words = ['s.env()', 's.borrow(self)'];
  args.forEach((t, i) => {
    const p = `p${i}`;
    params.push(`${ctype(t)} ${p}`);
    if (t === 'J' || t === 'D') {
      if (words.length % 2) words.push('0u');
      if (t === 'J') words.push(`(uint32_t)(uint64_t)${p}`, `(uint32_t)((uint64_t)${p} >> 32)`);
      else words.push(`emu_dlo(${p})`, `emu_dhi(${p})`);
    } else if (t === 'F') words.push(`emu_fbits(${p})`);
    else if (t[0] === 'L' || t[0] === '[') words.push(`s.borrow(${p})`);
    else if (t === 'Z' || t === 'C') words.push(`(uint32_t)${p}`);
    else words.push(`(uint32_t)(int32_t)${p}`);
  });
  const sym = PREFIX + name;
  const render = name === 'NativeRender' ? ', true' : '';
  const rt = ctype(ret);
  let body = `    static uint32_t fn;\n    Scope s(env, &fn, "${sym}"${render});\n    uint32_t a[] = {${words.join(', ')}};\n`;
  const call = `s.call(a, ${words.length})`;
  if (rt === 'void') body += `    ${call};\n`;
  else if (ret === 'J') body += `    return (jlong)${call};\n`;
  else if (ret === 'D') body += `    uint64_t r = ${call}; jdouble d; memcpy(&d, &r, 8); return d;\n`;
  else if (ret === 'F') body += `    uint32_t r = (uint32_t)${call}; jfloat f; memcpy(&f, &r, 4); return f;\n`;
  else if (ret[0] === 'L' || ret[0] === '[') body += `    return (${rt})s.ret_obj((uint32_t)${call});\n`;
  else body += `    return (${rt})(uint32_t)${call};\n`;
  out += `\nextern "C" JNIEXPORT ${rt} JNICALL ${sym}(${params.join(', ')}) {\n${body}}\n`;
}
// Helpers first, so the file compiles in one pass.
out = out.replace('using emu::Scope;\n', `using emu::Scope;
[[maybe_unused]] static inline uint32_t emu_fbits(float f) { uint32_t b; memcpy(&b, &f, 4); return b; }
[[maybe_unused]] static inline uint32_t emu_dlo(double d) { uint64_t b; memcpy(&b, &d, 8); return (uint32_t)b; }
[[maybe_unused]] static inline uint32_t emu_dhi(double d) { uint64_t b; memcpy(&b, &d, 8); return (uint32_t)(b >> 32); }
`);
fs.writeFileSync(outPath, out);
console.log(`gen-exports: ${exportsList.length} trampolines; native methods with no guest export: ${noExport.join(', ') || 'none'}`);
